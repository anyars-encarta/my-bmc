import { Authenticated, Refine } from "@refinedev/core";
import { DevtoolsPanel, DevtoolsProvider } from "@refinedev/devtools";
import { RefineKbar, RefineKbarProvider } from "@refinedev/kbar";

import routerProvider, {
  DocumentTitleHandler,
  NavigateToResource,
  UnsavedChangesNotifier,
} from "@refinedev/react-router";
import { BrowserRouter, Outlet, Route, Routes } from "react-router";
import { lazy, Suspense, useEffect, useState } from "react";
import "./App.css";
import { appResources } from "./constants/resources";
import { ErrorComponent } from "./components/refine-ui/layout/error-component";
import { Layout } from "./components/refine-ui/layout/layout";
import { Toaster } from "./components/refine-ui/notification/toaster";
import { useNotificationProvider } from "./components/refine-ui/notification/use-notification-provider";
import { ThemeProvider } from "./components/refine-ui/theme/theme-provider";
import { IdleLock } from "./components/IdleLock";
import { ApprovalQueueList, ApprovalReviewPage } from "./pages/approvals";
import {
  CategoryCreate,
  CategoryEdit,
  CategoryList,
  CategoryShow,
} from "./pages/categories";
import { DashboardPage } from "./pages/dashboard";
import { DisbursementList } from "./pages/disbursements";
import { ForgotPassword } from "./pages/forgot-password";
import { Login } from "./pages/login";
import { OrgUnitList } from "./pages/org-units";
import {
  PaymentCreate,
  PaymentEdit,
  PaymentList,
  PaymentShow,
} from "./pages/payments";
import { SetupCreate, SetupEdit, SetupShow } from "./pages/setup";
import { StaffCreate, StaffEdit, StaffList, StaffShow } from "./pages/staff";
import CreateUser from "./pages/users/create";
import EditUser from "./pages/users/edit";
import ListUsers from "./pages/users/list";
import ShowUser from "./pages/users/show";
import { authProvider } from "./providers/auth";
import { accessControlProvider } from "./providers/accessControl";
import { dataProvider } from "./providers/data";
import { SetupRecord } from "./types/domain";
import { BACKEND_BASE_URL } from "./constants";
import { RouteLoading } from "./components/refine-ui/layout/route-loading";
import HostingCriticalInfoModal from "./components/HostingCriticalInfoModal";

const HostingRenewalPage = lazy(
  () => import("./pages/hosting-renewal/hosting"),
);

const getPublicApiBase = () =>
  BACKEND_BASE_URL.replace(/\/+$/, "").replace(/\/api$/, "");

const formatPathSegment = (value: string) =>
  value.replace(/[-_]/g, " ").replace(/\b\w/g, (char) => char.toUpperCase());

const brandedTitle = ({
  resource,
  pathname,
  autoGeneratedTitle,
}: {
  resource?: { meta?: { label?: string } };
  pathname?: string;
  autoGeneratedTitle: string;
}) => {
  const resourceLabel =
    typeof resource?.meta?.label === "string" ? resource.meta.label.trim() : "";

  if (resourceLabel) {
    return `Encarta | ${resourceLabel}`;
  }

  if (pathname) {
    const segment = pathname.split("/").filter(Boolean).at(-1);

    if (segment) {
      return `Encarta | ${formatPathSegment(segment)}`;
    }
  }

  if (autoGeneratedTitle && autoGeneratedTitle.toLowerCase() !== "refine") {
    return `Encarta | ${autoGeneratedTitle}`;
  }

  return "Encarta | Finance Desk";
};

function App() {
  const [showSplash, setShowSplash] = useState(true);
  const notificationProvider = useNotificationProvider();
  const [info, setInfo] = useState<SetupRecord | null>(null);
  const [splashLogoLoaded, setSplashLogoLoaded] = useState(false);

  useEffect(() => {
    const loadInfo = async () => {
      try {
        const response = await fetch(
          `${getPublicApiBase()}/public/hosting-renewal/info`,
        );
        if (response.status === 401 || response.status === 403) {
          setInfo(null);
          return;
        }
        const payload = (await response.json()) as {
          success?: boolean;
          data?: SetupRecord;
          error?: string;
        };

        if (!response.ok || !payload.success) {
          throw new Error(payload.error || "Failed to load splash info");
        }

        const splashData = payload.data ?? null;
        setInfo(
          splashData
            ? {
                ...splashData,
                facilityName:
                  splashData.facilityName ??
                  splashData.facilityName ??
                  "Encarta",
                logoUrl: splashData.logoUrl ?? undefined,
              }
            : null,
        );
      } catch {
        setInfo(null);
      }
    };

    void loadInfo();
  }, []);

  useEffect(() => {
    const timer = window.setTimeout(() => {
      setShowSplash(false);
    }, 1800); // show splash for at least 1.8 seconds

    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    setSplashLogoLoaded(false);
  }, [info?.logoUrl]);

  if (showSplash) {
    const splashName = info?.facilityName ?? "Encarta";
    const splashLogoUrl = info?.logoUrl?.trim() || "";

    return (
      <div className="startup-splash" role="status" aria-live="polite">
        <div className="startup-splash-inner">
          <div className="startup-loader-ring" aria-hidden="true" />
          <div className="startup-logo-wrap relative overflow-hidden rounded-sm">
            {splashLogoUrl ? (
              <img
                src={splashLogoUrl}
                alt={splashName}
                className={`startup-logo ${
                  splashLogoLoaded ? "opacity-100" : "opacity-0"
                }`}
                onLoad={() => setSplashLogoLoaded(true)}
                onError={() => setSplashLogoLoaded(false)}
              />
            ) : null}
          </div>
        </div>
      </div>
    );
  }

  return (
    <ThemeProvider>
      <BrowserRouter>
        <RefineKbarProvider>
          <DevtoolsProvider>
            <Refine
                dataProvider={dataProvider}
                authProvider={authProvider}
                accessControlProvider={accessControlProvider}
                notificationProvider={notificationProvider}
                routerProvider={routerProvider}
                resources={appResources.map((resource) => ({
                  name: resource.name,
                  list: resource.list,
                  create: resource.create,
                  edit: resource.edit,
                  show: resource.show,
                  meta: {
                    label: resource.label,
                    icon: <resource.icon className="h-4 w-4" />,
                    canDelete: resource.canDelete,
                  },
                }))}
                options={{
                  syncWithLocation: true,
                  warnWhenUnsavedChanges: true,
                  projectId: "fFxMzl-ygw30s-D1GNyg",
                }}
              >
                <DocumentTitleHandler handler={brandedTitle} />
                <Routes>
                  <Route
                    path="/hosting-renewal"
                    element={
                      <Suspense
                        fallback={
                          <RouteLoading label="Loading hosting renewal..." />
                        }
                      >
                        <HostingRenewalPage />
                      </Suspense>
                    }
                  />
                  <Route
                    element={
                      <Authenticated key="guest-routes" fallback={<Outlet />}>
                        <NavigateToResource resource="dashboard" />
                      </Authenticated>
                    }
                  >
                    <Route path="login" element={<Login />} />
                  </Route>

                  <Route path="forgot-password" element={<ForgotPassword />} />

                  <Route
                    element={
                      <Authenticated
                        key="protected-routes"
                        redirectOnFail="/login"
                      >
                        <>
                          <HostingCriticalInfoModal setupInfo={info} />
                          <Layout>
                            <Outlet />
                          </Layout>
                        </>
                      </Authenticated>
                    }
                  >
                      <Route
                        index
                        element={<NavigateToResource resource="dashboard" />}
                      />
                      <Route path="dashboard" element={<DashboardPage />} />
                      <Route path="staff">
                        <Route index element={<StaffList />} />
                        <Route path="create" element={<StaffCreate />} />
                        <Route path="edit/:id" element={<StaffEdit />} />
                        <Route path="show/:id" element={<StaffShow />} />
                      </Route>
                      <Route path="org-units" element={<OrgUnitList />} />
                      <Route path="categories">
                        <Route index element={<CategoryList />} />
                        <Route path="create" element={<CategoryCreate />} />
                        <Route path="edit/:id" element={<CategoryEdit />} />
                        <Route path="show/:id" element={<CategoryShow />} />
                      </Route>
                      <Route path="payments">
                        <Route index element={<PaymentList />} />
                        <Route path="create" element={<PaymentCreate />} />
                        <Route path="edit/:id" element={<PaymentEdit />} />
                        <Route path="show/:id" element={<PaymentShow />} />
                      </Route>
                      <Route path="setup">
                        <Route index element={<SetupShow />} />
                        <Route path="create" element={<SetupCreate />} />
                        <Route path="edit/:id" element={<SetupEdit />} />
                        <Route path="show/:id" element={<SetupShow />} />
                      </Route>
                      <Route path="users">
                        <Route index element={<ListUsers />} />
                        <Route path="create" element={<CreateUser />} />
                        <Route path="edit/:id" element={<EditUser />} />
                        <Route path="show/:id" element={<ShowUser />} />
                      </Route>
                      <Route path="approvals">
                        <Route index element={<ApprovalQueueList />} />
                        <Route path=":id" element={<ApprovalReviewPage />} />
                      </Route>
                      <Route
                        path="disbursements"
                        element={<DisbursementList />}
                      />
                      <Route path="*" element={<ErrorComponent />} />
                  </Route>
                </Routes>

                <Toaster />
                <IdleLock />
                <RefineKbar />
                <UnsavedChangesNotifier />
              </Refine>
              <DevtoolsPanel />
          </DevtoolsProvider>
        </RefineKbarProvider>
      </BrowserRouter>
    </ThemeProvider>
  );
}

export default App;
