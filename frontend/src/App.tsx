const RECORD_REFERENCE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const formatPathSegment = (value: string) =>
  value.replace(/[-_]/g, " ").replace(/\b\w/g, (char) => char.toUpperCase());

const brandedTitle = ({
  resource,
  pathname,
  autoGeneratedTitle,
}: {
  resource?: { meta?: { label?: string } };
  pathname?: string;
  autoGeneratedTitle: string;
}) => {
  const resourceLabel =
    typeof resource?.meta?.label === "string" ? resource.meta.label.trim() : "";

  if (resourceLabel) {
    return `Encarta | ${resourceLabel}`;
  }

  if (pathname) {
    // Record references in the path are never shown in the page title.
    const segment = pathname
      .split("/")
      .filter((part) => part && !RECORD_REFERENCE.test(part))
      .at(-1);

    if (segment) {
      return `Encarta | ${formatPathSegment(segment)}`;
    }
  }

  if (autoGeneratedTitle && autoGeneratedTitle.toLowerCase() !== "refine") {
    return `Encarta | ${autoGeneratedTitle}`;
  }

  return "Encarta | Hospital Management Suite";
};

